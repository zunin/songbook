// smoke-node.mjs — offline Node smoke test for the assembled PDF assets.
// Verifies that the docstrip-generated songs.sty / size12.clo and the BaKoMa
// fonts compile the standalone songs fixture in the GlyphTeX engine and
// produce the same PDF text as the native Tectonic reference.
// Usage: node smoke-node.mjs <assets-dir> <fixtures-dir>
import { readFileSync, writeFileSync, readdirSync, statSync } from "node:fs";
import { execFileSync } from "node:child_process";
import { join, basename, resolve } from "node:path";
// The vendored engine's imports use the WebCrypto `crypto` global (WASM
// random_get). Node < 19 does not expose it by default; provide it from the
// crypto core module so the smoke runs on any supported node version.
import { webcrypto } from "node:crypto";
if (!globalThis.crypto) globalThis.crypto = webcrypto;
import { pathToFileURL } from "node:url";

const assetsDir = resolve(process.argv[2]);
const fixturesDir = process.argv[3];

// 1. load the vendored engine from the built assets
const engineMod = await import(new URL(`file://${assetsDir}/engine/index.js`).href);
const TexEngine = engineMod.TexEngine;

// 2. wasm + bundle
const wasm = new Uint8Array(readFileSync(`${assetsDir}/engine/tectonic.wasm`));
const engine = await TexEngine.load(wasm);

function walk(dir, cb) {
  for (const e of readdirSync(dir)) {
    const p = join(dir, e);
    if (statSync(p).isDirectory()) walk(p, cb);
    else cb(e, p);
  }
}

// 3. bundle.tar.gz -> files (Node has zlib + a tiny tar reader)
const { gzipSync, gunzipSync } = await import("node:zlib");
function parseTar(data) {
  const files = new Map();
  let off = 0;
  while (off + 512 <= data.length) {
    const name = data.subarray(off, off + 100).indexOf(0) > 0
      ? data.subarray(off, off + 100).subarray(0, data.subarray(off, off + 100).indexOf(0)).toString()
      : "";
    const size = parseInt(data.subarray(off + 124, off + 136).toString().replace(/\0.*$/, "").trim(), 8) || 0;
    const type = String.fromCharCode(data[off + 156]);
    if (type === "0" || type === "\0") files.set(name, data.subarray(off + 512, off + 512 + size));
    off += 512 + Math.ceil(size / 512) * 512;
  }
  return files;
}
const bundleFiles = parseTar(gunzipSync(readFileSync(`${assetsDir}/engine/bundle.tar.gz`)));
for (const [name, data] of bundleFiles) engine.addFile(name, data);

// 4. pack.tar.gz (generated songs.sty, size12.clo, fonts)
const packFiles = parseTar(gunzipSync(readFileSync(`${assetsDir}/pack/pack.tar.gz`)));
for (const [name, data] of packFiles) engine.addFile(name, data);
console.log(`smoke: bundle=${bundleFiles.size} pack=${packFiles.size} files loaded`);

// 5. compile the standalone fixture
const tex = readFileSync(`${fixturesDir}/let-it-be.tex`, "utf8");
engine.addFile("main.tex", tex);
const t0 = Date.now();
const result = engine.compile({ entry: "main.tex", paper: "a4" });
const compileMs = Date.now() - t0;
const pdf = engine.pdf();
const missing = result.missingFiles || [];
console.log(`smoke: status=${result.status} pdf=${pdf ? pdf.length : "MISSING"} B compile=${compileMs} ms missing=${missing.length}`);

if (!pdf || result.status !== "spotless") {
  console.error("smoke: FAILED", { status: result.status, missing, diagnostics: result.diagnostics });
  process.exit(1);
}

// 6. compare extracted text against the pinned native reference
writeFileSync("/tmp/pdf-engine-smoke-out.pdf", pdf);
const got = execFileSync("pdftotext", ["/tmp/pdf-engine-smoke-out.pdf", "-"]).toString();
const want = readFileSync(`${fixturesDir}/let-it-be-reference.txt`, "utf8");
if (got.trim() !== want.trim()) {
  console.error("smoke: PDF text differs from native reference");
  process.exit(1);
}
console.log("smoke: PDF text matches native Tectonic reference — PASS");

// ---------------------------------------------------------------------------
// 7. multi-song book fixture (ADR0019 fitness function), driven through the
// DEPLOYED worker module so the smoke exercises the real multi-pass index
// pipeline: LaTeX pass 1 writes `<index>.sxd`, the worker converts it with
// the songbook wasm (`songbook-core::songidx`, the port of the pinned
// `songidx.lua`), feeds the `.sbx` back and recompiles; pass 2 typesets the
// real index entries. The extracted text must match
// `demo-book-reference.txt`, a reference generated by the same three-step
// pipeline NATIVELY in the devcontainer (tectonic → `texlua songidx.lua` →
// tectonic; exact commands in fixtures/README.md) — the same byte-exact gate
// as the let-it-be reference above. The placeholder index is a failure now,
// not a tolerance: it cannot match the reference.
const bookTex = readFileSync(`${fixturesDir}/demo-book.tex`, "utf8");
const wantBookText = readFileSync(`${fixturesDir}/demo-book-reference.txt`, "utf8");

// The worker expects a browser worker environment: a `self` with `location`
// and `postMessage`, and fetches of same-origin asset URLs. Node resolves
// the deployed layout as file:// URLs, which its fetch does not support, so
// the shim serves file: URLs from disk and delegates everything else.
const assetsWorkerUrl = pathToFileURL(join(assetsDir, "pdf-worker.js"));
const realFetch = globalThis.fetch;
const workerMessages = [];
globalThis.fetch = async (input, init) => {
  const url = String(input instanceof URL ? input.href : input);
  if (url.startsWith("file:")) {
    const data = readFileSync(new URL(url));
    const type = url.endsWith(".wasm") ? "application/wasm" : "application/octet-stream";
    return new Response(data, { status: 200, headers: { "Content-Type": type } });
  }
  return realFetch(input, init);
};
globalThis.self = {
  location: new URL(assetsWorkerUrl),
  postMessage: (m) => workerMessages.push(m),
};
await import(assetsWorkerUrl);

// Drives one request/response exchange with the worker's onmessage handler.
function workerRequest(msg, timeoutMs = 300000) {
  return new Promise((resolve, reject) => {
    const start = workerMessages.length;
    const timer = setTimeout(() => reject(new Error(`worker timed out on ${msg.type}`)), timeoutMs);
    const poll = () => {
      while (workerMessages.length > start) {
        const m = workerMessages.shift();
        if (["ready", "result", "poisoned", "error"].includes(m.type)) {
          clearTimeout(timer);
          resolve(m);
          return;
        }
      }
      setTimeout(poll, 10);
    };
    poll();
    self.onmessage({ data: msg });
  });
}

const initMsg = await workerRequest({ type: "init" });
console.log(`smoke: worker ready (init ${Math.round(initMsg.timings.totalInitMs)} ms)`);

const tb0 = Date.now();
const bookMsg = await workerRequest({ type: "compile", id: 1, tex: bookTex, jobname: "main" });
const bookMs = Date.now() - tb0;
if (bookMsg.type !== "result") {
  console.error(`smoke: book FAILED (${bookMsg.type})`, bookMsg.message || "");
  process.exit(1);
}
const bookPdf = bookMsg.bytes;
const bookMissing = bookMsg.missingFiles || [];
console.log(`smoke: book status=${bookMsg.status} pdf=${bookPdf ? bookPdf.length : "MISSING"} B compile=${bookMs} ms missing=${bookMissing.length}`);

if (!bookPdf || bookMsg.status !== "spotless") {
  console.error("smoke: book FAILED (compile)", {
    status: bookMsg.status,
    missing: bookMissing,
    diagnostics: bookMsg.diagnostics,
  });
  process.exit(1);
}

writeFileSync("/tmp/pdf-engine-smoke-book.pdf", bookPdf);
const bookText = execFileSync("pdftotext", ["/tmp/pdf-engine-smoke-book.pdf", "-"]).toString();

// pdftotext emits one form feed (\f) after every page, including the last
// (verified empirically: the 1-page let-it-be fixture yields exactly 1 \f at
// end-of-output), so the page count equals the number of \f characters.
const bookPages = (bookText.match(/\f/g) || []).length;

// Secondary cross-check of that convention with pdfinfo when it is installed.
let pdfinfoPages = null;
try {
  const info = execFileSync("pdfinfo", ["/tmp/pdf-engine-smoke-book.pdf"]).toString();
  const m = info.match(/^Pages:\s+(\d+)\s*$/m);
  if (m) pdfinfoPages = parseInt(m[1], 10);
} catch (err) {
  if (err.code !== "ENOENT") throw err;
  console.log("smoke: book pdfinfo not installed — skipping page-count cross-check");
}
if (pdfinfoPages !== null) {
  console.log(`smoke: book pages=${bookPages} (pdfinfo: ${pdfinfoPages})`);
  if (pdfinfoPages !== bookPages) {
    console.error(`smoke: book FAILED (page-count cross-check): \\f count=${bookPages} vs pdfinfo=${pdfinfoPages}`);
    process.exit(1);
  }
} else {
  console.log(`smoke: book pages=${bookPages}`);
}

// The primary gate: byte-exact text against the native three-step reference
// (same comparison as the let-it-be native reference above).
if (bookText.trim() !== wantBookText.trim()) {
  const gotLines = bookText.trim().split("\n");
  const wantLines = wantBookText.trim().split("\n");
  let firstDiff = -1;
  for (let i = 0; i < Math.max(gotLines.length, wantLines.length); i++) {
    if (gotLines[i] !== wantLines[i]) {
      firstDiff = i;
      break;
    }
  }
  console.error("smoke: book FAILED (byte-exact text vs native reference)");
  console.error(`smoke:   got ${gotLines.length} lines, want ${wantLines.length} lines` +
    (firstDiff >= 0 ? `, first difference at line ${firstDiff + 1}:` : ":"));
  if (firstDiff >= 0) {
    for (let i = Math.max(0, firstDiff - 2); i < firstDiff + 3; i++) {
      console.error(`smoke:   got[${i}]  ${JSON.stringify(gotLines[i] ?? "<eof>")}`);
      console.error(`smoke:  want[${i}]  ${JSON.stringify(wantLines[i] ?? "<eof>")}`);
    }
  }
  console.error("smoke:   (diagnose: pipeline pass count? stale .sbx intermediates? see pdf-worker.js index pipeline)");
  process.exit(1);
}
console.log("smoke: book PDF text matches native three-step reference (songidx pipeline) — byte-exact");

console.log(`smoke: book PASS status=spotless pages=${bookPages} index=byte-exact-vs-native`);
