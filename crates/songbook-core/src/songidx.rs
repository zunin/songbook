        assert_eq!(upper_bytes("café".as_bytes()), "CAFÉ".as_bytes());
        assert_eq!(upper_bytes("ß ǆ ı İ".as_bytes()), "ß Ǆ I İ".as_bytes());
        // U+00B5 uppercases to bytes that are not valid UTF-8 in texlua.
        assert_eq!(upper_bytes("µ".as_bytes()), [0xFF, 0xBF, 0xBE, 0x9C]);
