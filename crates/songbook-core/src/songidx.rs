//! Song-index conversion (`.sxd` → `.sbx`, ADR0019): a faithful Rust port of
//! the `songs` package's `songidx.lua` title-index path, pinned at
//! `web/dist/pdf-assets/sources/songs.zip` (`songidx/songidx.lua`, v3.1).
//!
//! The browser book pipeline (ADR0018/0019) runs LaTeX pass 1, which makes
//! the package write `<index>.sxd` data files; this module converts one into
//! the `.sbx` file a second LaTeX pass typesets, replacing the external
//! `texlua songidx.lua` step. Everything here mirrors `songidx.lua` exactly —
//! including its quirks — because the output must be byte-identical to what
//! the pinned script produces (P4; golden-tested in `tests/fixtures/songidx/`
//! against native runs under `LC_ALL=C`).
//!
//! What is ported (everything reachable from the book pipeline's output):
//!
//! * the `TITLE INDEX DATA FILE` format: 3-line groups (entry text, song
//!   number, hyperlink name) written by the package's `\SB@addtoindex`. The
//!   chord index is a title index too: `\indexentry[chordidx]{Am}` writes the
//!   entry text `*Am`, and the leading `*` marks an alternate entry, emitted
//!   as `\idxaltentry` instead of `\idxentry`;
//! * entry cleanup: a trailing-whitespace strip (`[^%s\\]%s+$`), a
//!   leading-whitespace strip that preserves a leading `*`, and article
//!   rotation ("The Beatles" → "Beatles,~The": `A`/`THE` matched
//!   case-insensitively, original case kept in the `,~` suffix);
//! * sorting: word-by-word over the macro-stripped, uppercased title; numbers
//!   (Lua `tonumber` grammar: decimals, exponents, hex, hex floats) sort
//!   before words and in numeric order; words compare byte-wise, which is
//!   the C-locale `strcoll` order native songidx runs under here; remaining
//!   ties prefer non-`*` entries, then input order;
//! * index blocks (`\begin{idxblock}{X}`), including `\#` for entries whose
//!   cleaned title has no word character, and the canonical-character rule
//!   that keeps a block's character when a later entry's start character
//!   sorts at-or-before it but is shorter;
//! * the `%prefix ` directive (`\titleprefixword`).
//!
//! What is deliberately *not* ported (unreachable from the book pipeline,
//! which only ever emits title-style indexes and no directives beyond
//! `%prefix`):
//!
//! * `AUTHOR INDEX DATA FILE` (author splitting via `grabauthor`) and
//!   `SCRIPTURE INDEX DATA FILE` (verse-range compaction): both are rejected
//!   with an error;
//! * the `%sep `, `%after `, and `%ignore ` directives: in the pinned
//!   songidx.lua these index `wt_sep`/`wt_after`/`wt_ignore`, which are never
//!   defined — native songidx 3.1 aborts with a Lua error on them (verified:
//!   `songidx.lua:406: ... table expected, got nil`). The port rejects them
//!   with a clear error instead of crashing;
//! * locale-dependent collation beyond the C locale: native songidx
//!   delegates order to `strcoll`, so a non-C locale changes its output.
//!   This port always compares bytes (C-locale order) and the goldens are
//!   generated with `LC_ALL=C`;
//! * two native non-terminations: when a sort comparison reaches word
//!   positions whose characters are word-ish (`%w`) but neither numeric nor
//!   alphabetic (e.g. titles led by `①`), both word prefixes compare empty
//!   and songidx.lua loops forever. The port advances one character and
//!   terminates instead; a single such entry still converts byte-identically
//!   (see `symbols.sxd`).

