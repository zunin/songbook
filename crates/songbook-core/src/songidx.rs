    #[test]
    fn rotation_follows_songidx_rules() {
        let defaults = |words: &[&str]| -> Vec<PrefixWord> {
            words
                .iter()
                .map(|w| PrefixWord {
                    bytes: w.as_bytes().to_vec(),
                    chars: w.chars().count(),
                })
                .collect()
        };
        let wt = defaults(&["A", "THE"]);
        assert_eq!(rotate(b"The Beatles", &wt).unwrap(), b"Beatles,~The");
        assert_eq!(rotate(b"A Day", &wt).unwrap(), b"Day,~A");
        assert_eq!(rotate(b"An Apple", &wt).unwrap(), b"An Apple");
        assert_eq!(rotate(b"Ain't She Sweet", &wt).unwrap(), b"Ain't She Sweet");
        assert_eq!(rotate(b"Theme Song", &wt).unwrap(), b"Theme Song");
        assert_eq!(rotate(b"A", &wt).unwrap(), b"A");
        assert_eq!(rotate(b"the low road", &wt).unwrap(), b"Low road,~the");
        assert_eq!(rotate(b"A  B Song", &wt).unwrap(), b"B Song,~A");
        assert_eq!(rotate(b"The \\& Song", &wt).unwrap(), b"\\& Song,~The");
        // The optional `%w?` can match nothing (no word char after `%W*`).
        assert_eq!(rotate("A →".as_bytes(), &wt).unwrap(), "→,~A".as_bytes());
        assert_eq!(rotate(b"*The X", &wt).unwrap(), b"*X,~The");
    }

